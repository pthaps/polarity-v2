-- Review and apply after the server has a service-role credential.
-- This transaction changes access only. It does not delete stored data.
begin;

create table if not exists public.analyses (
  id bigint generated by default as identity primary key,
  url text not null,
  title text,
  replies jsonb not null default '[]',
  created_at timestamptz default now()
);

alter table public.analyses enable row level security;


create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  url text not null default '',
  title text,
  rating text not null,
  comment text,
  created_at timestamptz default now()
);

alter table public.feedback enable row level security;

drop policy if exists "Allow anonymous insert" on public.analyses;
drop policy if exists "Allow anonymous select" on public.analyses;
drop policy if exists "Allow anonymous insert feedback" on public.feedback;
drop policy if exists "Allow anonymous select feedback" on public.feedback;
revoke all on public.analyses, public.feedback from public, anon, authenticated;
grant select, insert on public.analyses, public.feedback to service_role;

commit;
